# ---------- 样式 ----------
def set_ea(style_or_run, ea, latin='Times New Roman'):
    f = style_or_run.font
    f.name = latin
    rpr = style_or_run._element.get_or_add_rPr() if hasattr(style_or_run, '_element') else None
    el = style_or_run.element if hasattr(style_or_run, 'element') else style_or_run._element
    rPr = el.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:eastAsia'), ea)

